"""Executable IF/3-only offline checker binding; never an implementation oracle."""
import argparse
import copy
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
from fixtures import catalog,materialize
from support import PREVIOUS,previous

sha=lambda b:hashlib.sha256(b).hexdigest()

def codes(v):
    if isinstance(v,dict):return set(v.get('reasons',[]))|set().union(*(codes(x) for k,x in v.items() if k!='reasons'))
    if isinstance(v,list):return set().union(*(codes(x) for x in v))
    return set()

def contains(v,value):
    if isinstance(v,dict):return any(contains(x,value) for x in v.values())
    if isinstance(v,list):return any(contains(x,value) for x in v)
    return v==value

def snapshot(root):return {p.relative_to(root).as_posix():sha(p.read_bytes()) for p in root.rglob('*') if p.is_file()}

def identities(checker,bundle,golden):
    return dict(tool=dict(name='bench_evidence.py',version='BE1-IF/3',sha256=sha(checker.read_bytes())),
      bundle=dict(path=str(bundle),manifest_sha256=sha((bundle/'manifest.json').read_bytes())),
      golden=dict(manifest_sha256=sha((golden/'MANIFEST').read_bytes()),sha256sums_sha256=sha((golden/'SHA256SUMS').read_bytes())))

def check(report,rc,e,ident):
    assert rc==e['exit'],('exit',rc,e['exit'])
    assert report['schema']=='digital-tape/be1-report/1'
    assert report['physical_run'] is e['physical_run'] and report['complete'] is False
    assert report['overall']==e['overall'],('overall',report['overall'],e['overall'])
    assert set(report['criteria'])==set(('F1','F2','F3','F4','F5'))
    assert report['criteria']['F3']['state']=='NOT_RUN' and report['criteria']['F4']['state']=='NOT_RUN'
    if e['criterion']:assert report['criteria'][e['criterion']]['state']==e['state']
    assert set(e['codes'])<=codes(report),('reason codes',set(e['codes'])-codes(report))
    for group,values in ident.items():
        for key,value in values.items():assert report[group][key]==value,('identity',group,key)
    for expected in e.get('retained',[]):
        obs=next(o for o in report['observations'] if o['id']==expected['id'])
        assert obs['state']==expected['state']
        assert contains(report['criteria'][e['criterion']]['superseded_failures'],expected['id'])
    assert all(c['state']!='PASS' for c in report['criteria'].values())

def fake_report(e,ident):
    r=dict(schema='digital-tape/be1-report/1',physical_run=e['physical_run'],complete=False,
      overall=e['overall'],reasons=list(e['codes']),observations=[],**copy.deepcopy(ident),
      criteria={x:dict(state='NOT_RUN',reasons=[],superseded_failures=[]) for x in ('F1','F2','F3','F4','F5')})
    if e['criterion']:r['criteria'][e['criterion']]['state']=e['state']
    for old in e.get('retained',[]):
        r['observations'].append(copy.deepcopy(old));r['criteria'][e['criterion']]['superseded_failures'].append(old['id'])
    return r

def execute(checker,bundle,golden,report,e):
    before=snapshot(bundle);log=report.with_suffix('.audit.json')
    p=subprocess.run([sys.executable,'-B',str(PREVIOUS/'guard.py'),str(checker),str(bundle),str(report),str(golden),str(log)],
      capture_output=True,timeout=30,env=dict(os.environ,PYTHONDONTWRITEBYTECODE='1'))
    assert not json.loads(log.read_text(encoding='utf-8')),'Denied/attempted external effect'
    assert before==snapshot(bundle),'Bundle bytes changed'
    raw=report.read_text(encoding='utf-8');r=json.loads(raw)
    def ordered(v):
        if isinstance(v,dict):return list(v)==sorted(v) and all(ordered(x) for x in v.values())
        if isinstance(v,list):return all(ordered(x) for x in v)
        return True
    assert ordered(r),'Report keys are not sorted'
    check(r,p.returncode,e,identities(checker,bundle,golden))
    return r

def selftest(golden,out):
    cs=catalog(previous.references(golden));assert len({c['name'] for c in cs})==len(cs)
    stub=out/'stub.py';stub.write_text('# harness double, not Product\n',encoding='utf-8')
    for c in cs:
        b=out/c['name'];materialize(c,b)
        ident=identities(stub,b,golden);check(fake_report(c['expected'],ident),c['expected']['exit'],c['expected'],ident)
    # Exercise the inherited execution guard with a fixed-report double. Identity
    # uses the source bytes actually run; it is not generated by any Product checker.
    c=cs[0];b=out/c['name'];e=c['expected']
    source="""import json,sys,hashlib
from pathlib import Path
p=Path(sys.argv[sys.argv.index('--out')+1])
r=json.loads(REPORT)
r['tool']['sha256']=hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
p.write_text(json.dumps(r,sort_keys=True)+'\\n',encoding='utf-8')
raise SystemExit(EXIT)
"""
    r=fake_report(e,identities(stub,b,golden))
    stub.write_text(source.replace('REPORT',repr(json.dumps(r))).replace('EXIT',str(e['exit'])),encoding='utf-8')
    execute(stub,b,golden,out/'double.json',e)
    controls=[]
    def reject(label,e,mut,rc=None):
        ident=identities(stub,b,golden);r=fake_report(e,ident);mut(r)
        try:check(r,e['exit'] if rc is None else rc,e,ident)
        except (AssertionError,KeyError,StopIteration):controls.append(label)
        else:raise AssertionError('Undetected control: '+label)
    retained=next(c['expected'] for c in cs if c['name']=='retry-retains-False-False')
    reject('retry-erases-exit',retained,lambda r:None,0)
    reject('retry-erases-overall',retained,lambda r:r.update(overall='CONSISTENT'))
    reject('retry-erases-observation',retained,lambda r:r.update(observations=[]))
    reject('retry-erases-failure-list',retained,lambda r:r['criteria']['F1'].update(superseded_failures=[]))
    failed=next(c['expected'] for c in cs if c['name']=='failed-verify-no-transcript')
    reject('missing-data-hides-failure',failed,lambda r:r['criteria']['F5'].update(state='NOT_RUN'))
    reject('missing-data-hides-reason',failed,lambda r:r['reasons'].remove('f5_verify_findings'))
    image=next(c['expected'] for c in cs if c['name']=='firmware-exact-path-conflict-rehashed')
    reject('firmware-conflict-hidden',image,lambda r:r.update(reasons=[]))
    reject('false-complete',e,lambda r:r.update(complete=True))
    reject('wrong-tool-identity',e,lambda r:r['tool'].update(sha256='0'*64))
    reject('wrong-bundle-identity',e,lambda r:r['bundle'].update(manifest_sha256='0'*64))
    return dict(mode='harness-selftest-only',fixture_cases=len(cs),controls_detected=controls,
                product_executed=False,physical_run=False,complete=False)

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--golden',type=Path,required=True);ap.add_argument('--out',type=Path,required=True)
    ap.add_argument('--checker',type=Path);ap.add_argument('--selftest',action='store_true');a=ap.parse_args()
    out=a.out.resolve();out.mkdir(parents=True,exist_ok=False);golden=a.golden.resolve()
    if a.selftest:
        assert not a.checker;result=selftest(golden,out)
    else:
        assert a.checker and a.checker.is_file(),'No implemented checker input was supplied'
        observations=[]
        for c in catalog(previous.references(golden)):
            b=out/c['name'];materialize(c,b)
            try:
                execute(a.checker.resolve(),b,golden,out/(c['name']+'.json'),c['expected']);observations.append(dict(case=c['name'],passed=True))
            except Exception as exc:observations.append(dict(case=c['name'],passed=False,error=repr(exc)))
        result=dict(mode='candidate-offline-check',checker_sha256=sha(a.checker.read_bytes()),cases=observations,
          passed=all(v['passed'] for v in observations),physical_run=False,complete=False)
    (out/'RESULT.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({k:v for k,v in result.items() if k!='cases'}));return 0 if result.get('passed',True) else 1

if __name__=='__main__':raise SystemExit(main())
